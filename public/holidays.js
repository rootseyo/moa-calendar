export function detectDefaultRegion() {
  try {
    const tz = (Intl.DateTimeFormat().resolvedOptions().timeZone || '').toLowerCase();
    if (tz.includes('seoul') || tz.includes('korea')) return 'KR';
    if (tz.includes('tokyo') || tz.includes('japan')) return 'JP';
    if (tz.includes('london') || tz.includes('britain')) return 'GB';
    if (tz.startsWith('america/') || tz.startsWith('us/')) return 'US';
  } catch {}
  try {
    const nav = (navigator.languages?.[0] || navigator.language || '').toLowerCase();
    if (nav.includes('ko') || nav.includes('kr')) return 'KR';
    if (nav.includes('ja') || nav.includes('jp')) return 'JP';
    if (nav.includes('gb') || nav.includes('uk')) return 'GB';
    if (nav.includes('en') || nav.includes('us')) return 'US';
  } catch {}
  return 'KR';
}

export function getActiveRegion() {
  try {
    const saved = localStorage.getItem('moa_region');
    if (saved === 'none') return 'none';
    if (saved && ['KR', 'US', 'JP', 'GB'].includes(saved)) return saved;
  } catch {}
  return detectDefaultRegion();
}

export function getActiveLocale() {
  try {
    if (document.documentElement.lang === 'en') return 'en';
  } catch {}
  try {
    const saved = localStorage.getItem('moa_language');
    if (saved === 'en' || saved === 'ko') return saved;
  } catch {}
  try {
    const nav = (navigator.languages?.[0] || navigator.language || '').toLowerCase();
    if (nav.startsWith('ko')) return 'ko';
  } catch {}
  return 'ko';
}

export function getRegionName(regionCode, lang = getActiveLocale()) {
  const isEn = lang === 'en';
  const found = HOLIDAY_REGIONS.find(r => r.code === regionCode);
  if (found) return isEn ? found.nameEn : found.nameKo;
  if (regionCode === 'none') return isEn ? 'No holidays' : '공휴일 없음';
  return regionCode;
}

export function getHoliday(dateKey, targetRegion = getActiveRegion(), targetLocale = getActiveLocale()) {
  if (targetRegion === 'none' || !dateKey) return null;
  const isEn = targetLocale === 'en';

  if (targetRegion === 'KR') {
    const koName = KOREA_HOLIDAYS[dateKey];
    if (!koName) return null;
    return isEn ? (KOREA_HOLIDAYS_EN[koName] || koName) : koName;
  }

  if (targetRegion === 'US') {
    const enName = US_HOLIDAYS[dateKey];
    if (!enName) return null;
    return isEn ? enName : (US_HOLIDAYS_KO[enName] || enName);
  }

  if (targetRegion === 'JP') {
    const jaName = JP_HOLIDAYS[dateKey];
    if (!jaName) return null;
    return isEn ? (JP_HOLIDAYS_EN[jaName] || jaName) : (JP_HOLIDAYS_KO[jaName] || jaName);
  }

  if (targetRegion === 'GB') {
    const enName = GB_HOLIDAYS[dateKey];
    if (!enName) return null;
    return isEn ? enName : (GB_HOLIDAYS_KO[enName] || enName);
  }

  return null;
}
